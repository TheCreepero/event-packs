[CmdletBinding()]
param(
    [Parameter()]
    [string]$RepoRoot
)

try {
    if (-not $RepoRoot) { $RepoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path }
    $repoRootPath = $RepoRoot.TrimEnd('\', '/')
    $hookInput = [Console]::In.ReadToEnd() | ConvertFrom-Json
    $toolName = [string]$hookInput.tool_name

    $generatedReason = 'is generated by build.ps1 -Generate (pictures: -ConvertPictures) from source/<pack>/. Change the source, or the plan that writes it, and generate again; see docs/source-format.md.'
    $syncedReason = 'is synced from the Modding Manager and is overwritten on the next sync. Change it in the Manager, or ask the user.'
    $protectedPaths = @(
        [PSCustomObject]@{ Pattern = 'source/*/pictures.json'; Reason = 'is written only by build.ps1 -FetchPicture, which records the licence it read from Wikimedia Commons.' },
        [PSCustomObject]@{ Pattern = 'wiki/Event-Pack-*.md'; Reason = $generatedReason },
        [PSCustomObject]@{ Pattern = 'tools/HoiModBuild.ps1'; Reason = $syncedReason },
        [PSCustomObject]@{ Pattern = 'tests/BuildEngine.Tests.ps1'; Reason = $syncedReason },
        [PSCustomObject]@{ Pattern = 'tests/Run-Tests.ps1'; Reason = $syncedReason },
        [PSCustomObject]@{ Pattern = 'tests/Knowledge.Tests.ps1'; Reason = $syncedReason },
        [PSCustomObject]@{ Pattern = '.github/workflows/ci.yml'; Reason = $syncedReason },
        [PSCustomObject]@{ Pattern = '.agents/skills/*'; Reason = 'is the Antigravity mirror written by build.ps1 -SyncMirrors. Edit .claude/skills/<skill>/SKILL.md instead; the PostToolUse hook syncs the mirror.' }
    )

    if ($toolName -in @('Edit', 'Write', 'MultiEdit', 'NotebookEdit')) {
        $filePath = [string]$hookInput.tool_input.file_path
        if (-not $filePath) { $filePath = [string]$hookInput.tool_input.notebook_path }
        if (-not $filePath) { exit 0 }
        if (-not [System.IO.Path]::IsPathRooted($filePath)) { $filePath = Join-Path $repoRootPath $filePath }
        $fullPath = [System.IO.Path]::GetFullPath($filePath)
        if (-not $fullPath.StartsWith($repoRootPath + '\', [System.StringComparison]::OrdinalIgnoreCase)) { exit 0 }
        $relativePath = $fullPath.Substring($repoRootPath.Length + 1).Replace('\', '/')
        if ($relativePath -match '^packs/[^/]+/' -and $relativePath -notmatch '^packs/[^/]+/(descriptor\.mod|thumbnail\.png)$') {
            [Console]::Error.WriteLine("$relativePath $generatedReason Only descriptor.mod and thumbnail.png of a pack are edited by hand.")
            exit 2
        }
        foreach ($protected in $protectedPaths) {
            if ($relativePath -like $protected.Pattern) {
                [Console]::Error.WriteLine("$relativePath $($protected.Reason)")
                exit 2
            }
        }
        exit 0
    }

    if ($toolName -in @('Bash', 'PowerShell')) {
        $command = [string]$hookInput.tool_input.command
        if (-not $command -or $command -notmatch '(^|[\s"''=(\\/])packs[\\/]|pictures\.json|Event-Pack-') { exit 0 }
        $singleBuildCall = '^\s*(&\s*)?((powershell|pwsh)(\.exe)?\s+(-\w+\s+)*-File\s+)?["'']?(\.[\\/])?build\.ps1["'']?(\s+-\w+(\s+("[^"]*"|''[^'']*''|[^\s;&|<>`$]+))?)*\s*$'
        if ($command -match $singleBuildCall) { exit 0 }
        if ($command -match '^\s*git\s' -and $command -notmatch '[;&|<>`$]') { exit 0 }
        $writePattern = 'Set-Content|Add-Content|Out-File|Clear-Content|WriteAll|\.Write\(|Copy-Item|Move-Item|Remove-Item|Rename-Item|New-Item|Set-Item|Export-|robocopy|xcopy|\bcopy\b|\bdel\b|\bren\b|sed\s+-i|\bcp\s|\bmv\s|\brm\s|\btee\b|\btouch\s|\bdd\s|\bpython|\bpy\s|\bnode\b|\bperl\b|\bruby\b|Invoke-WebRequest|\bcurl\b|\bwget\b|(?<![2&])>(?!\s*\$null)'
        if ($command -match $writePattern) {
            [Console]::Error.WriteLine('The command writes and names a pack folder, a pictures.json or a generated wiki page: a pack changes only through build.ps1 (-Generate, -ConvertPictures, -FetchPicture), run as a command of its own. See docs/source-format.md.')
            exit 2
        }
        exit 0
    }

    exit 0
} catch {
    exit 0
}
