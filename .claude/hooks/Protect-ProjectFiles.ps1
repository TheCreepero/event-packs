[CmdletBinding()]
param(
    [Parameter()]
    [string]$RepoRoot
)

try {
    if (-not $RepoRoot) { $RepoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path }
    $repoRootPath = $RepoRoot.TrimEnd('\', '/')
    $hookInput = [Console]::In.ReadToEnd() | ConvertFrom-Json
    $toolName = [string]$hookInput.tool_name

    $generatedReason = 'is generated by build.ps1 -Generate (pictures: -ConvertPictures) from source/<pack>/. Change the source, or the plan that writes it, and generate again; see docs/source-format.md.'
    $syncedReason = 'is synced from the Modding Manager and is overwritten on the next sync. Change it in the Manager, or ask the user.'
    $thumbnailReason = 'is written only by the Modding Manager''s Scripts\Showcase\New-HoiThumbnail.ps1 -Path <repo> -Pack <pack> -Apply, from assets/thumbnail.json (a plan''s thumbnail step).'
    $planSourceReason = 'is written only by build.ps1 -ApplyPlan -Plan <plan> from the blocks of a plan in docs/plans/ (and created by -NewPack); see docs/source-format.md, "Plans". Put the change into a plan and apply it.'
    $protectedPaths = @(
        [PSCustomObject]@{ Pattern = 'source/*/pictures.json'; Reason = 'is written only by build.ps1 -FetchPicture, which records the licence it read from Wikimedia Commons, and -RemovePicture, which drops a row no event uses.' },
        [PSCustomObject]@{ Pattern = 'source/*/events.json'; Reason = $planSourceReason },
        [PSCustomObject]@{ Pattern = 'source/*/fact-sheets.md'; Reason = $planSourceReason },
        [PSCustomObject]@{ Pattern = 'wiki/Event-Pack-*.md'; Reason = $generatedReason },
        [PSCustomObject]@{ Pattern = 'tools/HoiModBuild.ps1'; Reason = $syncedReason },
        [PSCustomObject]@{ Pattern = 'tests/BuildEngine.Tests.ps1'; Reason = $syncedReason },
        [PSCustomObject]@{ Pattern = 'tests/Run-Tests.ps1'; Reason = $syncedReason },
        [PSCustomObject]@{ Pattern = 'tests/Knowledge.Tests.ps1'; Reason = $syncedReason },
        [PSCustomObject]@{ Pattern = 'tools/HoiImageSources.ps1'; Reason = $syncedReason },
        [PSCustomObject]@{ Pattern = 'tests/ImageSources.Tests.ps1'; Reason = $syncedReason },
        [PSCustomObject]@{ Pattern = 'tests/fixtures/image-sources/*'; Reason = $syncedReason },
        [PSCustomObject]@{ Pattern = '.github/workflows/ci.yml'; Reason = $syncedReason },
        [PSCustomObject]@{ Pattern = '.agents/skills/*'; Reason = 'is the Antigravity mirror written by build.ps1 -SyncMirrors. Edit .claude/skills/<skill>/SKILL.md instead; the PostToolUse hook syncs the mirror.' }
    )

    if ($toolName -in @('Edit', 'Write', 'MultiEdit', 'NotebookEdit')) {
        $filePath = [string]$hookInput.tool_input.file_path
        if (-not $filePath) { $filePath = [string]$hookInput.tool_input.notebook_path }
        if (-not $filePath) { exit 0 }
        if (-not [System.IO.Path]::IsPathRooted($filePath)) { $filePath = Join-Path $repoRootPath $filePath }
        $fullPath = [System.IO.Path]::GetFullPath($filePath)
        if (-not $fullPath.StartsWith($repoRootPath + '\', [System.StringComparison]::OrdinalIgnoreCase)) { exit 0 }
        $relativePath = $fullPath.Substring($repoRootPath.Length + 1).Replace('\', '/')
        if ($relativePath -match '^packs/[^/]+/thumbnail\.png$') {
            [Console]::Error.WriteLine("$relativePath $thumbnailReason")
            exit 2
        }
        if ($relativePath -match '^packs/[^/]+/' -and $relativePath -notmatch '^packs/[^/]+/descriptor\.mod$') {
            [Console]::Error.WriteLine("$relativePath $generatedReason Only descriptor.mod of a pack is edited by hand.")
            exit 2
        }
        foreach ($protected in $protectedPaths) {
            if ($relativePath -like $protected.Pattern) {
                [Console]::Error.WriteLine("$relativePath $($protected.Reason)")
                exit 2
            }
        }
        exit 0
    }

    if ($toolName -in @('Bash', 'PowerShell')) {
        $command = [string]$hookInput.tool_input.command
        $protectedPathPattern = '(^|[\s"''=(\\/])packs[\\/]|pictures\.json|(^|[\s"''=(\\/])(events\.json|fact-sheets\.md)|(^|[\s"''=(\\/])Event-Pack-[^\s"''\\/]*\.md|tools[\\/]Hoi(ModBuild|ImageSources)\.ps1|tests[\\/](BuildEngine\.Tests|Run-Tests|Knowledge\.Tests|ImageSources\.Tests)\.ps1|tests[\\/]fixtures[\\/]image-sources|\.github[\\/]workflows[\\/]ci\.yml|\.agents[\\/]skills'
        if (-not $command -or $command -notmatch $protectedPathPattern) { exit 0 }
        $singleBuildCall = '^\s*(&\s*)?((powershell|pwsh)(\.exe)?\s+(-\w+\s+)*-File\s+)?["'']?(\.[\\/])?build\.ps1["'']?(\s+-\w+(\s+("[^"]*"|''[^'']*''|[^\s;&|<>`$]+))?)*\s*$'
        $writePattern = 'Set-Content|Add-Content|Out-File|Clear-Content|WriteAll|\.Write\(|Copy-Item|Move-Item|Remove-Item|Rename-Item|New-Item|Set-Item|Export-|robocopy|xcopy|\bcopy\b|\bdel\b|\bren\b|sed\s+-i|\bcp\s|\bmv\s|\brm\s|\btee\b|\btouch\s|\bdd\s|\bpython|\bpy\s|\bnode\b|\bperl\b|\bruby\b|Invoke-WebRequest|\bcurl\b|\bwget\b|(?<![2&])>(?!\s*\$null)'
        $plainReadPattern = '^(?!.*\s-(OutVariable|ov|PipelineVariable|pv|ErrorVariable|ev|WarningVariable|wv|InformationVariable|iv)\b)\s*(Get-Content|Get-ChildItem|Get-Item|Get-FileHash|Test-Path|Resolve-Path|Select-String|gc|gci|cat|ls|dir|type|grep|head|tail|wc)\s[^|=]*$'
        $unquotedCommand = $command -replace '"[^"]*"|''[^'']*''', '""'
        $splitIsUnreliable = $command -match '`|\\["'']|\\\r?\n|\$\(|<<|@["'']' -or $unquotedCommand -match '[(){}]|(?<![&>])&(?!&)'

        function Split-CommandStatement {
            param([string]$CommandText)

            $statements = [System.Collections.Generic.List[string]]::new()
            $currentStatement = [System.Text.StringBuilder]::new()
            $openQuote = [char]0
            for ($index = 0; $index -lt $CommandText.Length; $index++) {
                $character = $CommandText[$index]
                $nextCharacter = if ($index + 1 -lt $CommandText.Length) { $CommandText[$index + 1] } else { [char]0 }
                if ($openQuote -ne [char]0) {
                    if ($character -eq $openQuote) { $openQuote = [char]0 }
                    [void]$currentStatement.Append($character)
                    continue
                }
                if ($character -eq [char]'"' -or $character -eq [char]"'") {
                    $openQuote = $character
                    [void]$currentStatement.Append($character)
                    continue
                }
                $isSeparator = $character -eq [char]';' -or $character -eq [char]"`n" -or $character -eq [char]"`r"
                $isDoubleOperator = ($character -eq [char]'&' -and $nextCharacter -eq [char]'&') -or ($character -eq [char]'|' -and $nextCharacter -eq [char]'|')
                if ($isSeparator -or $isDoubleOperator) {
                    $statements.Add($currentStatement.ToString())
                    [void]$currentStatement.Clear()
                    if ($isDoubleOperator) { $index++ }
                    continue
                }
                [void]$currentStatement.Append($character)
            }
            $statements.Add($currentStatement.ToString())
            return @($statements | ForEach-Object { $_.Trim() } | Where-Object { $_ })
        }

        $statementsToJudge = if ($splitIsUnreliable) { @($command) } else { @(Split-CommandStatement -CommandText $command) }
        $protectedPathCarried = $false
        foreach ($statement in $statementsToJudge) {
            $namesProtectedPath = $statement -match $protectedPathPattern
            if ($statement -match $singleBuildCall) { continue }
            if ($statement -match '^\s*git\s' -and $statement -notmatch '[;&|<>`$]') { continue }
            if ($statement -match $writePattern) {
                if ($namesProtectedPath -or $protectedPathCarried) {
                    [Console]::Error.WriteLine("The statement '$statement' writes to a protected path: a pack folder, a pictures.json, an events.json, a fact-sheets.md or a generated wiki page changes only through build.ps1 (-Generate, -ConvertPictures, -FetchPicture, -ApplyPlan, -NewPack) run as a statement of its own (see docs/source-format.md); a pack's thumbnail.png only through the Modding Manager's Scripts\Showcase\New-HoiThumbnail.ps1 -Path <repo> -Pack <pack> -Apply, from assets/thumbnail.json; a file synced from the Manager or the .agents mirror changes at its source. Git statements and other statements in the same command are not affected.")
                    exit 2
                }
                continue
            }
            if ($namesProtectedPath -and $statement -notmatch $plainReadPattern) { $protectedPathCarried = $true }
        }
        exit 0
    }

    exit 0
} catch {
    exit 0
}
