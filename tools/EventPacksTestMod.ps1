function Get-EpTestModName {
    return 'event_packs_test'
}

function New-EpTestEffectsText {
    param([Parameter(Mandatory = $true)]$Packs)

    $lines = [System.Collections.Generic.List[string]]::new()
    $lines.Add('# Generated by build.ps1 -TestMod from source/<pack>/events.json; not part of any pack.')
    $lines.Add('# A scripted effect named d_<name> is the console command <name> [AUTO-043].')
    foreach ($pack in @($Packs)) {
        $eventNumbers = @($pack.Events | ForEach-Object { [int]$_.id } | Sort-Object)
        $lines.Add('')
        $lines.Add("# $($pack.DisplayName): $($pack.Namespace)_all fires its $($eventNumbers.Count) events, $($pack.Namespace)_reset lets the weekly anchor fire them again.")
        $lines.Add("d_$($pack.Namespace)_all = {")
        $lines.Add("`t$($pack.Tag) = {")
        foreach ($eventNumber in $eventNumbers) {
            $lines.Add("`t`tset_country_flag = $($pack.Namespace)_fired_$eventNumber")
            $lines.Add("`t`tcountry_event = { id = $($pack.Namespace).$eventNumber }")
        }
        $lines.Add("`t}")
        $lines.Add('}')
        $lines.Add("d_$($pack.Namespace)_reset = {")
        $lines.Add("`t$($pack.Tag) = {")
        foreach ($eventNumber in $eventNumbers) {
            $lines.Add("`t`tclr_country_flag = $($pack.Namespace)_fired_$eventNumber")
        }
        $lines.Add("`t}")
        $lines.Add('}')
    }
    return (($lines -join "`r`n") + "`r`n")
}

function New-EpTestDescriptorText {
    param([string]$Path)

    $lines = @(
        'version="1.0"',
        'tags={',
        "`t`"Utilities`"",
        '}',
        'name="Event Packs Test (dev only)"',
        'supported_version="1.19.*"'
    )
    if ($Path) {
        $lines += 'path="' + $Path.Replace('\', '/') + '"'
    }
    return (($lines -join "`r`n") + "`r`n")
}

function Invoke-EpTestMod {
    param(
        [Parameter(Mandatory = $true)][string]$RepoRoot,
        [Parameter(Mandatory = $true)][string[]]$Pack,
        [Parameter(Mandatory = $true)][string]$ModDir,
        [switch]$DryRun
    )

    $packs = @($Pack | ForEach-Object { Get-EpPack -RepoRoot $RepoRoot -Pack $_ })
    $testModRoot = Join-Path $RepoRoot ('artifacts\' + (Get-EpTestModName))
    $launcherFile = Join-Path $ModDir ((Get-EpTestModName) + '.mod')
    $files = [ordered]@{
        (Join-Path $testModRoot 'descriptor.mod')                              = New-EpTestDescriptorText
        (Join-Path $testModRoot 'common\scripted_effects\ep_test_effects.txt') = New-EpTestEffectsText -Packs $packs
        $launcherFile                                                         = New-EpTestDescriptorText -Path $testModRoot
    }
    if ($DryRun) {
        foreach ($filePath in $files.Keys) {
            Write-Host "Would write $filePath" -ForegroundColor Cyan
        }
    }
    else {
        if (Test-Path -LiteralPath $testModRoot) {
            Remove-Item -LiteralPath $testModRoot -Recurse -Force
        }
        foreach ($filePath in $files.Keys) {
            Write-EpText -Path $filePath -Text $files[$filePath]
        }
        Write-Host "Wrote the test mod to $testModRoot and its launcher file $launcherFile." -ForegroundColor Green
    }
    Write-Host "Enable 'Event Packs Test (dev only)' beside the pack, play as its country, and in the console:"
    foreach ($testPack in $packs) {
        Write-Host "  $($testPack.Namespace)_all     fires the $(@($testPack.Events).Count) $($testPack.DisplayName) events to $($testPack.Tag)"
        Write-Host "  $($testPack.Namespace)_reset   clears their guard flags"
    }
    return 0
}
